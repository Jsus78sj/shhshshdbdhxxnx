// أداة تعديل android/app/build.gradle(.kts) بعد `flutter create`:
//  1) ربط android/app/proguard-rules.pro بنسخة release (كان يُنسخ دون أن يُربط).
//  2) توقيع النسخة بمفتاح الإصدار إن وُجد android/key.properties، وإلا مفتاح debug.
// الأداة آمنة للتكرار (idempotent) وتدعم Kotlin DSL وGroovy، وتحفظ نسخة .bs8110.bak.
//
// الاستخدام (من جذر المشروع):  dart tool/patch_android_gradle.dart [android]
//
// ملاحظة: تعليقات gradle المولَّدة بالإنجليزية عمداً (ASCII) لتفادي مشاكل الترميز على Windows.
import 'dart:io';

const String _marker = 'BS8110-RELEASE-CONFIG';

int _matchBrace(String s, int openIdx) {
  var depth = 0;
  for (var i = openIdx; i < s.length; i++) {
    final c = s[i];
    if (c == '{') {
      depth++;
    } else if (c == '}') {
      depth--;
      if (depth == 0) return i;
    }
  }
  return -1;
}

RegExpMatch? _find(RegExp re, String s, int start) {
  final it = re.allMatches(s, start).iterator;
  if (it.moveNext()) return it.current;
  return null;
}

String _patch(String content, {required bool kotlin}) {
  if (content.contains(_marker)) return content;
  var s = content;

  final androidMatch =
      RegExp(r'^android\s*\{', multiLine: true).firstMatch(s);
  if (androidMatch == null) {
    throw const FormatException('android { } block not found');
  }
  final androidOpen = androidMatch.end - 1;

  final buildTypesMatch = _find(RegExp(r'buildTypes\s*\{'), s, androidOpen);
  if (buildTypesMatch == null) {
    throw const FormatException('buildTypes { } block not found');
  }
  final releaseMatch =
      _find(RegExp(r'\brelease\s*\{'), s, buildTypesMatch.end);
  if (releaseMatch == null) {
    throw const FormatException('release { } block not found');
  }
  final releaseOpen = releaseMatch.end - 1;
  final releaseClose = _matchBrace(s, releaseOpen);
  if (releaseClose < 0) {
    throw const FormatException('unbalanced braces in release block');
  }

  final lineStart = s.lastIndexOf('\n', releaseMatch.start) + 1;
  final baseIndent =
      RegExp(r'^[ \t]*').firstMatch(s.substring(lineStart))!.group(0)!;
  final ind = baseIndent + '    ';

  // ---- (1) داخل release: التوقيع + proguardFiles (نبدأ من نهاية الملف لتبقى الفهارس صحيحة)
  var body = s.substring(releaseOpen + 1, releaseClose);
  body = body.replaceAll(
    RegExp(r'^[ \t]*signingConfig\b.*\n?', multiLine: true),
    '',
  );
  final String releaseAdd;
  if (kotlin) {
    releaseAdd = '\n' +
        ind +
        '// ' +
        _marker +
        ': sign with android/key.properties when present, otherwise the debug key\n' +
        ind +
        'signingConfig = if (bs8110KeyPropsFile.exists()) signingConfigs.getByName("bs8110Release") else signingConfigs.getByName("debug")\n' +
        ind +
        'proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")';
  } else {
    releaseAdd = '\n' +
        ind +
        '// ' +
        _marker +
        ': sign with android/key.properties when present, otherwise the debug key\n' +
        ind +
        'signingConfig bs8110KeyPropsFile.exists() ? signingConfigs.bs8110Release : signingConfigs.debug\n' +
        ind +
        "proguardFiles getDefaultProguardFile('proguard-android-optimize.txt'), 'proguard-rules.pro'";
  }
  s = s.substring(0, releaseOpen + 1) +
      releaseAdd +
      body +
      s.substring(releaseClose);

  // ---- (2) signingConfigs مباشرة بعد "android {"
  final String signingBlock;
  if (kotlin) {
    signingBlock = '\n'
        '    signingConfigs {\n'
        '        create("bs8110Release") {\n'
        '            if (bs8110KeyPropsFile.exists()) {\n'
        '                keyAlias = bs8110KeyProps.getProperty("keyAlias")\n'
        '                keyPassword = bs8110KeyProps.getProperty("keyPassword")\n'
        '                storeFile = file(bs8110KeyProps.getProperty("storeFile"))\n'
        '                storePassword = bs8110KeyProps.getProperty("storePassword")\n'
        '            }\n'
        '        }\n'
        '    }\n';
  } else {
    signingBlock = '\n'
        '    signingConfigs {\n'
        '        bs8110Release {\n'
        '            if (bs8110KeyPropsFile.exists()) {\n'
        "                keyAlias bs8110KeyProps.getProperty('keyAlias')\n"
        "                keyPassword bs8110KeyProps.getProperty('keyPassword')\n"
        "                storeFile file(bs8110KeyProps.getProperty('storeFile'))\n"
        "                storePassword bs8110KeyProps.getProperty('storePassword')\n"
        '            }\n'
        '        }\n'
        '    }\n';
  }
  s = s.substring(0, androidOpen + 1) +
      signingBlock +
      s.substring(androidOpen + 1);

  // ---- (3) قراءة key.properties قبل "android {"
  final String preamble;
  if (kotlin) {
    preamble = '// ' +
        _marker +
        ' (generated by tool/patch_android_gradle.dart)\n'
            'val bs8110KeyPropsFile = rootProject.file("key.properties")\n'
            'val bs8110KeyProps = Properties()\n'
            'if (bs8110KeyPropsFile.exists()) {\n'
            '    FileInputStream(bs8110KeyPropsFile).use { bs8110KeyProps.load(it) }\n'
            '}\n\n';
  } else {
    preamble = '// ' +
        _marker +
        ' (generated by tool/patch_android_gradle.dart)\n'
            "def bs8110KeyPropsFile = rootProject.file('key.properties')\n"
            'def bs8110KeyProps = new Properties()\n'
            'if (bs8110KeyPropsFile.exists()) {\n'
            '    bs8110KeyPropsFile.withInputStream { bs8110KeyProps.load(it) }\n'
            '}\n\n';
  }
  final androidMatch2 =
      RegExp(r'^android\s*\{', multiLine: true).firstMatch(s)!;
  s = s.substring(0, androidMatch2.start) +
      preamble +
      s.substring(androidMatch2.start);

  // Kotlin DSL: داخل build.gradle.kts تُفسَّر كلمة `java` كامتداد Gradle وليس كحزمة JDK،
  // لذلك نستورد الصنفين بأسمائهما القصيرة في أول الملف (الاستيراد يجب أن يسبق أي كود).
  if (kotlin) {
    final imports = StringBuffer();
    if (!s.contains('import java.util.Properties')) {
      imports.write('import java.util.Properties\n');
    }
    if (!s.contains('import java.io.FileInputStream')) {
      imports.write('import java.io.FileInputStream\n');
    }
    if (imports.isNotEmpty) {
      s = imports.toString() + s;
    }
  }

  return s;
}

void main(List<String> args) {
  final androidDir = args.isNotEmpty ? args.first : 'android';
  final ktsFile = File('$androidDir/app/build.gradle.kts');
  final groovyFile = File('$androidDir/app/build.gradle');

  final File target;
  final bool kotlin;
  if (ktsFile.existsSync()) {
    target = ktsFile;
    kotlin = true;
  } else if (groovyFile.existsSync()) {
    target = groovyFile;
    kotlin = false;
  } else {
    stderr.writeln('ERROR: no android/app/build.gradle(.kts) found in "$androidDir". '
        'Run `flutter create --platforms=android .` first.');
    exit(1);
  }

  final original = target.readAsStringSync();
  if (original.contains(_marker)) {
    stdout.writeln('[patch_android_gradle] ${target.path}: already patched - skipping.');
    return;
  }

  try {
    final patched = _patch(original, kotlin: kotlin);
    final backup = File('${target.path}.bs8110.bak');
    if (!backup.existsSync()) backup.writeAsStringSync(original);
    target.writeAsStringSync(patched);
    final hasKey = File('$androidDir/key.properties').existsSync();
    stdout.writeln('[patch_android_gradle] ${target.path}: patched (proguard-rules.pro linked).');
    stdout.writeln(hasKey
        ? '[patch_android_gradle] android/key.properties found -> release build will be signed with YOUR key.'
        : '[patch_android_gradle] WARNING: android/key.properties not found -> APK will be signed with the DEBUG key '
            '(fine for personal install, NOT for Google Play). See RELEASE_GUIDE.md.');
  } on FormatException catch (e) {
    stderr.writeln('[patch_android_gradle] WARNING: could not patch ${target.path}: ${e.message}');
    stderr.writeln('The build continues, but proguard-rules.pro is NOT linked and the APK is debug-signed.');
    stderr.writeln('Apply the manual steps in RELEASE_GUIDE.md ("Manual gradle setup").');
  }
}
